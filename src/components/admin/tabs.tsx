"use client";

import { useState } from "react";
import { cn } from "@/lib/utils";

/** Minimal accessible tabs for admin sections. */
export function Tabs({ tabs }: { tabs: { id: string; label: string; content: React.ReactNode }[] }) {
  const [active, setActive] = useState(tabs[0]?.id);
  return (
    <div>
      <div role="tablist" className="mb-5 flex gap-1 overflow-x-auto rounded-full border bg-white p-1">
        {tabs.map((t) => (
          <button
            key={t.id}
            role="tab"
            type="button"
            id={`tab-${t.id}`}
            aria-selected={active === t.id}
            aria-controls={`panel-${t.id}`}
            onClick={() => setActive(t.id)}
            className={cn("whitespace-nowrap rounded-full px-4 py-2 text-sm font-medium transition", active === t.id ? "bg-forest-700 text-white" : "text-forest-800 hover:bg-forest-50")}
          >
            {t.label}
          </button>
        ))}
      </div>
      {tabs.map((t) => (
        <div key={t.id} role="tabpanel" id={`panel-${t.id}`} aria-labelledby={`tab-${t.id}`} hidden={active !== t.id}>
          {t.content}
        </div>
      ))}
    </div>
  );
}
